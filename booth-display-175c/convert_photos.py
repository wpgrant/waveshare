#!/usr/bin/env python3
"""Convert photos into booth_photos.h for the booth-display sketch.

Usage:
    python3 convert_photos.py photo1.jpg photo2.png photo3.jpg

Each image is centre-cropped to a square, resized to 466x466, and stored
as RGB565 (the display's native format). The output file goes in the same
folder as this script, next to the .ino file, and the sketch picks it up
automatically on the next compile.

Notes:
- The round screen clips the corners, so keep faces/subjects near the
  centre of each photo.
- Each photo costs ~435 KB of flash. The board has 32 MB, so a handful of
  photos is fine; keep it under ~10.
- Requires Pillow:  pip install Pillow

To go back to the text-only intro slide, just delete booth_photos.h.
"""

import sys
from pathlib import Path

SIZE = 466

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")


def to_rgb565(img: Image.Image) -> list[int]:
    img = img.convert("RGB")
    pixels = []
    for r, g, b in img.getdata():
        pixels.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return pixels


def main(paths: list[str]) -> None:
    if not paths:
        sys.exit("Usage: python3 convert_photos.py photo1.jpg [photo2.jpg ...]")

    out_lines = [
        "// Generated by convert_photos.py - do not edit by hand.",
        "// Re-run the script whenever you change the photos.",
        "#pragma once",
        "",
    ]
    arrays = []
    for i, p in enumerate(paths):
        path = Path(p)
        if not path.exists():
            sys.exit(f"Not found: {p}")
        img = Image.open(path)
        # Centre-crop to square, then resize to the display.
        w, h = img.size
        side = min(w, h)
        img = img.crop(((w - side) // 2, (h - side) // 2,
                        (w + side) // 2, (h + side) // 2))
        img = img.resize((SIZE, SIZE), Image.LANCZOS)
        px = to_rgb565(img)
        name = f"booth_photo_{i}"
        arrays.append(name)
        out_lines.append(f"const uint16_t {name}[{SIZE * SIZE}] = {{")
        for j in range(0, len(px), 12):
            out_lines.append("  " + ",".join(f"0x{v:04X}" for v in px[j:j + 12]) + ",")
        out_lines.append("};")
        out_lines.append("")
        print(f"{path.name}: {w}x{h} -> {SIZE}x{SIZE} ({len(px)} pixels)")

    out_lines.append(f"#define BOOTH_PHOTO_COUNT {len(arrays)}")
    out_lines.append("const uint16_t *BOOTH_PHOTOS[] = {"
                     + ", ".join(arrays) + "};")
    out = Path(__file__).parent / "booth_photos.h"
    out.write_text("\n".join(out_lines) + "\n")
    print(f"Wrote {out} with {len(arrays)} photo(s). Recompile the sketch.")


if __name__ == "__main__":
    main(sys.argv[1:])
